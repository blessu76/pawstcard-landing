"""/releases/ — the app's release notes page, built from content/releases.json with the ipe_web_kit releases module.

The app's Settings tile opens https://pawstcard.ipe.rest/releases/#<version>-<build>. GitHub Pages answers an unknown path with
its 404.html (HTTP 404) and the app's web sheet does not read the HTTP status, so the page must exist in the repo.
"""
import html
import json
import os
import re
import sys
import unittest
from pathlib import Path

REPO = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(REPO / "scripts"))
import build_releases as br  # noqa: E402

APP_NOTE_ENV = "PAWSTCARD_APP_RELEASE_NOTE"  # optional: the app repo's release_notes/<build>.json, compared item by item


def read(rel):
    return (REPO / rel).read_text(encoding="utf-8")


def releases():
    return json.loads(read("content/releases.json"))["releases"]


class Page(unittest.TestCase):
    def test_page_exists_and_is_in_sync_with_the_notes(self):
        self.assertEqual(br.build(REPO, check_only=True), [])

    def test_every_published_build_has_a_card_with_the_app_anchor_and_its_english_items(self):
        page = read("releases/index.html")
        for r in releases():
            self.assertIn('<article class="ipe-rel" id="%s-%s">' % (r["version"], r["build"]), page)
            self.assertIn("<h2 class=\"ipe-rel__head\"><span class=\"ipe-rel__build\">%s (%s)</span></h2>" % (r["version"], r["build"]), page)
            for line in r["notes"]["en"]:
                self.assertIn("<li>%s</li>" % html.escape(line), page)
            self.assertEqual(len(re.findall(r"<li>", page)), sum(len(x["notes"]["en"]) for x in releases()))

    def test_korean_is_stored_but_never_rendered(self):
        # the shared ipe-localtime script carries Korean comments (in every journal page too) — look at the rest of the page
        page = re.sub(r"<script>.*?</script>", "", read("releases/index.html"), flags=re.S)
        for r in releases():
            self.assertTrue(r["notes"]["ko"])
        self.assertNotRegex(page, r"[\u3131-\u318e\uac00-\ud7a3]")

    def test_date_only_notes_are_not_localised_to_an_invented_time(self):
        self.assertNotRegex(read("releases/index.html"), r'<time data-ipe-time datetime="\d{4}-\d\d-\d\dT00:00\+09:00">\d{4}-\d\d-\d\d</time>')

    def test_page_is_noindex_and_stays_out_of_the_sitemap(self):
        page = read("releases/index.html")
        self.assertIn('<meta name="robots" content="noindex, follow">', page)
        self.assertIn("generated by scripts/build_releases.py", page)
        self.assertNotIn("/releases/", read("sitemap.xml"))

    def test_the_release_contract_lets_publish_commit_the_generated_page(self):
        cfg = json.loads(read("ipe_release.json"))
        self.assertEqual(cfg["releases_file"], "content/releases.json")
        self.assertEqual(cfg["style"], "releases")
        self.assertIn("releases/index.html", cfg["commit_paths"])
        self.assertIn("scripts/build_releases.py", cfg["build"])

    @unittest.skipUnless(os.environ.get(APP_NOTE_ENV), "set %s to the app's release_notes/<build>.json" % APP_NOTE_ENV)
    def test_items_and_build_match_the_app_copy(self):
        app = json.loads(Path(os.environ[APP_NOTE_ENV]).read_text(encoding="utf-8"))
        web = next(r for r in releases() if r["id"] == app["id"])
        self.assertEqual((web["version"], web["build"]), (app["version"], app["build"]))
        for lang in app["notes"]:
            self.assertEqual(web["notes"][lang], app["notes"][lang], lang)


if __name__ == "__main__":
    unittest.main()
