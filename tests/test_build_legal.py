"""Legal pages (/privacy/ /terms/ /about/ /contact/): built from legal/*.md, linked from every footer and the signup form, in sync."""
import re
import sys
import tempfile
import shutil
import unittest
from pathlib import Path

REPO = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(REPO / "scripts"))
import build_journal as bj  # noqa: E402
import build_legal as bl  # noqa: E402

SLUGS = [p[0] for p in bl.PAGES]


def read(rel):
    return (REPO / rel).read_text(encoding="utf-8")


class Pages(unittest.TestCase):
    def test_every_page_exists_and_is_in_sync_with_its_manuscript(self):
        problems, _ = bl.build(REPO, check_only=True)
        self.assertEqual(problems, [])

    def test_pages_carry_the_manuscript_text_and_no_draft_banner_or_reviewer_notes(self):
        for slug in SLUGS:
            html = read("%s/index.html" % slug)
            self.assertEqual(html.count("<h1>"), 1, slug)
            self.assertNotRegex(html, r"(?i)draft\s+—|pending review|not legal advice", slug)
            self.assertNotIn("Differences from the existing drafts", html, slug)
            self.assertIn("generated by scripts/build_legal.py", html, slug)
            self.assertIn("/journal/assets/journal.css?v=%s" % bj.asset_v(REPO), html, slug)  # cache-busting follows the stylesheet

    def test_privacy_names_every_third_party_the_site_really_loads(self):
        privacy, landing = read("privacy/index.html"), read("index.html")
        for needle, name in (("googletagmanager.com", "Google Analytics"), ("connect.facebook.net", "Meta Pixel"),
                             ("cloudflareinsights.com", "Cloudflare"), ("api.web3forms.com", "Web3Forms"), ("fonts.googleapis.com", "Google Fonts")):
            self.assertIn(needle, landing, needle)
            self.assertIn(name, privacy, name)

    def test_privacy_table_renders_as_a_scrollable_table(self):
        html = read("privacy/index.html")
        self.assertIn('<div class="table-wrap"><table>', html)
        self.assertGreaterEqual(html.count("<th>"), 4)

    def test_terms_keeps_the_ai_note_limits_from_the_store_listing(self):
        terms = read("terms/index.html")
        self.assertIn("You can edit every word", terms)
        self.assertIn("nothing is sent until you approve it", terms)
        self.assertIn("Medication entries use fixed wording instead of AI", terms)

    def test_open_questions_are_reported_not_hidden(self):
        problems, warnings = bl.build(REPO, check_only=True)
        self.assertEqual(problems, [])
        self.assertTrue(all("Davy 확인" in w for w in warnings))

    def test_differences_section_is_cut_and_markers_counted_only_in_the_published_part(self):
        src = "# T\n\nbody [Davy 확인: x]\n\n## Differences from the old drafts\n\nnote [Davy 확인: y]\n"
        self.assertNotIn("note", bl.page_body(src))
        self.assertEqual(bl.open_questions(src), 1)


class Links(unittest.TestCase):
    def pages(self):
        yield "index.html"
        yield "404.html"
        yield "journal/index.html"
        yield from ("%s/index.html" % s for s in SLUGS)
        yield from (str(p.relative_to(REPO)) for p in sorted((REPO / "journal" / "en").glob("*/index.html")))

    def test_every_footer_links_privacy_and_terms(self):
        for rel in self.pages():
            html = read(rel)
            foot = html[html.index("<footer"):html.index("</footer>")]
            self.assertIn('href="/privacy/"', foot, rel)
            self.assertIn('href="/terms/"', foot, rel)
            if rel != "404.html":
                self.assertIn('href="/about/"', foot, rel)
                self.assertIn('href="/contact/"', foot, rel)

    def test_signup_form_links_the_privacy_policy_before_the_survey(self):
        html = read("index.html")
        line = re.search(r'<p class="privacy">(.*?)</p>', html, re.S).group(1)
        self.assertIn('By signing up you agree to our <a href="/privacy/">Privacy Policy</a>', line)
        self.assertLess(html.index('id="ea-form"'), html.index(line))


class MarkdownTables(unittest.TestCase):
    def test_table_with_escaped_inline_markup_and_no_html_injection(self):
        out = bj.markdown("| A | B |\n|---|---|\n| `x` | **y** <b> |\n\nafter")
        self.assertIn("<th>A</th><th>B</th>", out)
        self.assertIn("<td><code>x</code></td><td><strong>y</strong> &lt;b&gt;</td>", out)
        self.assertTrue(out.endswith("<p>after</p>"))

    def test_a_pipe_line_without_a_separator_row_stays_a_paragraph(self):
        self.assertEqual(bj.markdown("| not a table |"), "<p>| not a table |</p>")


class Sync(unittest.TestCase):
    def test_build_writes_exactly_the_four_pages(self):
        tmp = Path(tempfile.mkdtemp())
        self.addCleanup(shutil.rmtree, tmp, True)
        shutil.copytree(REPO / "legal", tmp / "legal")
        (tmp / "journal" / "assets").mkdir(parents=True)
        shutil.copy(REPO / bj.CSS_REL, tmp / bj.CSS_REL)
        problems, _ = bl.build(tmp)
        self.assertEqual(problems, [])
        self.assertEqual(sorted(p.parent.name for p in tmp.glob("*/index.html")), sorted(SLUGS))
        for slug in SLUGS:
            self.assertEqual((tmp / slug / "index.html").read_text(encoding="utf-8"), read("%s/index.html" % slug))


if __name__ == "__main__":
    unittest.main()
