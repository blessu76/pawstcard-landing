#!/usr/bin/env python3
"""Build /releases/ (the app's release notes, English) from content/releases.json with the ipe_web_kit releases module.

    python3 scripts/build_releases.py            # write releases/index.html
    python3 scripts/build_releases.py --check    # write nothing; fail if the page is missing, out of date, or the notes fail the kit lint

content/releases.json is written by the app side (`python3 vendor/ipe_web_kit/releases.py publish …`, see ipe_release.json), never by hand.
The app's Settings tile opens https://pawstcard.ipe.rest/releases/#<version>-<build>; GitHub Pages answers an unknown path with its
404.html page (HTTP 404) and the app's web sheet does not look at the HTTP status, so this page MUST exist before an app build points at it.
The site is English only: ko text stays in content/releases.json (the kit requires it) but is not rendered.
"""
import argparse
import re
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))
import build_journal as bj  # noqa: E402
from ipe_web_kit import releases as kit  # noqa: E402
from ipe_web_kit.ui import inline_css  # noqa: E402

ROOT = Path(__file__).resolve().parent.parent
SRC = "content/releases.json"
OUT = "releases/index.html"
TITLE = "Release notes — Pawstcard"
H1 = "Release notes"
DESC = "What changed in each Pawstcard app build."


def page_url():
    return "%s/releases/" % bj.SITE


DATE_ONLY_TIME = re.compile(r'<time data-ipe-time datetime="(\d{4}-\d\d-\d\d)T00:00\+09:00">\1</time>')


def cards(site):
    """Kit cards. A note with a date but no time of day must not be "localised" (the kit would invent 00:00 KST and show
    the day before to a reader in the Americas), so a date-only <time> loses its data-ipe-time marker."""
    return DATE_ONLY_TIME.sub(r'<time datetime="\1">\1</time>', kit.cards_html(site, "en"))


def render(site, v):
    url = page_url()
    head = bj.head(TITLE, DESC, url, v, True, "", alternates=bj.alt_links(url))
    head = head.replace("edit journal/posts/*.md and rebuild", "edit content/releases.json via the kit's releases.py publish")
    head = head.replace(bj.GEN_MARK, "generated by scripts/build_releases.py")
    head = head.replace("</head>", re.sub(r"/\*.*?\*/\s*", "", inline_css(), flags=re.S) + "\n</head>", 1)  # kit comments are Korean
    return (head + f"""<main class="wrap article-wrap">
  <article class="article">
    <header class="article-head">
      <h1>{bj.esc(H1)}</h1>
    </header>
    <div class="releases">
{cards(site)}
    </div>
  </article>
</main>
""" + bj.footer())  # the footer already inlines ipe-localtime


def build(root, check_only=False):
    """Returns the list of problems. Writes the page unless check_only."""
    root = Path(root).resolve()
    site = kit.load_site(root / SRC)
    problems = []
    if not kit.visible(site):
        problems.append("%s: no published release — /releases/ would be an empty page" % SRC)
    for res in kit.lint_site(site, ["en", "ko"], check_all=True, site_langs=["en"]):
        if res.level == "error":
            problems.append("%s: %s %s" % (SRC, res.code, res.msg))
    out = render(site, bj.asset_v(root))
    target = root / OUT
    if check_only:
        if not target.exists() or target.read_text(encoding="utf-8") != out:
            problems.append("%s is missing or out of date — run scripts/build_releases.py" % OUT)
    elif not problems:
        target.parent.mkdir(parents=True, exist_ok=True)
        target.write_text(out, encoding="utf-8")
    return problems


def main(argv=None):
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--root", default=str(ROOT))
    ap.add_argument("--check", action="store_true", help="write nothing; fail if the page is missing or out of date")
    a = ap.parse_args(argv)
    problems = build(a.root, a.check)
    if problems:
        print("releases: errors\n  " + "\n  ".join(problems), file=sys.stderr)
        return 1
    print("releases: %s" % ("OK" if a.check else "built"))
    return 0


if __name__ == "__main__":
    sys.exit(main())
