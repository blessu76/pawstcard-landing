#!/usr/bin/env python3
"""Build /privacy/ and /terms/ from legal/*.md.

    python3 scripts/build_legal.py            # write <slug>/index.html for each page
    python3 scripts/build_legal.py --check    # write nothing; fail if a generated page is missing or out of date

Same page shell, markdown subset, styles and ?v= cache-busting as the journal (imports scripts/build_journal.py).
Open questions are written as [confirm …] markers in the manuscript; they are highlighted, never removed.
The build fails if a source still carries an HTML comment, a Korean character or an internal reference.
"""
import argparse
import re
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))
import build_journal as bj  # noqa: E402

ROOT = Path(__file__).resolve().parent.parent
SRC_DIR = "legal"
PAGES = [
    # slug, <h1>, <title>, meta description
    ("privacy", "Privacy Policy", "Privacy Policy — Pawstcard",
     "How the Pawstcard app and the web pages it creates collect, use, share and delete personal information, and how to ask us about it."),
    ("terms", "Terms of Use", "Terms of Use — Pawstcard",
     "The terms for using the Pawstcard app and the web pages it creates: what the Service is, your content, AI drafts, and what is not promised."),
]
INTERNAL_RE = re.compile(r"<!--|-->|[ㄱ-ㆎ가-힣]|Quill|_ipe")
CONFIRM_RE = re.compile(r"\[confirm[^\]]*\]")
BANNER = ('<p class="draft-banner" role="note"><strong>DRAFT — not legally reviewed.</strong> '
          'Not legal advice. Highlighted [confirm …] items are unresolved and must be settled before this page is published.</p>\n')


def page_url(slug):
    return "%s/%s/" % (bj.SITE, slug)


def internal_problems(src):
    return sorted(set(INTERNAL_RE.findall(src)))


def render_page(slug, h1, title, desc, src, v):
    url = page_url(slug)
    body = CONFIRM_RE.sub(lambda m: '<mark class="confirm">%s</mark>' % m.group(0), bj.markdown(src))
    data = {"@context": "https://schema.org", "@type": "WebPage", "name": h1, "description": desc, "url": url,
            "inLanguage": "en", "isPartOf": {"@type": "WebSite", "name": "Pawstcard", "url": bj.SITE + "/"},
            "publisher": dict(bj.ORG, logo=dict(bj.APP_ICON))}
    head = bj.head(title, desc, url, v, False, bj.ld(data), alternates=bj.alt_links(url))
    head = head.replace(bj.GEN_MARK, "generated by scripts/build_legal.py")
    return (head + f"""<main class="wrap article-wrap">
  <article class="article legal">
    <header class="article-head">
      <h1>{bj.esc(h1)}</h1>
    </header>
    <div class="prose">
{BANNER}{body}
    </div>
  </article>
</main>
""" + bj.footer())


def build(root, check_only=False):
    """Returns a list of problems. Writes pages unless check_only."""
    root = Path(root).resolve()
    v = bj.asset_v(root)
    problems = []
    for slug, h1, title, desc in PAGES:
        src_path = root / SRC_DIR / (slug + ".md")
        if not src_path.exists():
            problems.append("%s: missing" % src_path.relative_to(root))
            continue
        src = src_path.read_text(encoding="utf-8")
        leaked = internal_problems(src)
        if leaked:
            problems.append("%s: internal text in the manuscript (%s)" % (src_path.relative_to(root), ", ".join(leaked)))
            continue
        out = render_page(slug, h1, title, desc, src, v)
        target = root / slug / "index.html"
        if check_only:
            if not target.exists() or target.read_text(encoding="utf-8") != out:
                problems.append("%s/index.html is missing or out of date — run scripts/build_legal.py" % slug)
        else:
            target.parent.mkdir(parents=True, exist_ok=True)
            target.write_text(out, encoding="utf-8")
    return problems


def main(argv=None):
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--root", default=str(ROOT))
    ap.add_argument("--check", action="store_true", help="write nothing; fail if a generated page is missing or out of date")
    a = ap.parse_args(argv)
    problems = build(a.root, a.check)
    if problems:
        print("legal: errors\n  " + "\n  ".join(problems), file=sys.stderr)
        return 1
    print("legal: %s — %d pages" % ("OK" if a.check else "built", len(PAGES)))
    return 0


if __name__ == "__main__":
    sys.exit(main())
