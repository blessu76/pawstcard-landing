#!/usr/bin/env python3
"""Build the static pages /privacy/ /terms/ /about/ /contact/ from legal/*.md.

    python3 scripts/build_legal.py            # write <slug>/index.html for each page
    python3 scripts/build_legal.py --check    # write nothing; fail if a generated page is missing or out of date

Same page shell, markdown subset, styles and ?v= cache-busting as the journal (it imports scripts/build_journal.py).
The text of a page is its legal/<slug>.md as written, minus the leading '# Title' (the template owns the <h1>) and
minus everything from a '## Differences' or '## Legal review pending' heading on (reviewer notes that are never published).
Internal notes must never reach a page: the build FAILS if the published part still has a `[Davy …]` marker, the word
"Davy", or any Korean text (pages are English only). Open legal questions live in the '## Legal review pending' list.
"""
import argparse
import re
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))
import build_journal as bj  # noqa: E402

ROOT = Path(__file__).resolve().parent.parent
SRC_DIR = "legal"
INTERNAL_RE = re.compile(r"Davy|[\u3131-\u318e\uac00-\ud7a3]")
PAGES = [
    # slug, <h1>, <title>, meta description
    ("privacy", "Privacy Policy", "Privacy Policy — Pawstcard",
     "What the Pawstcard website collects when you join the waitlist or visit, who receives it, how long we keep it, and how to have it deleted."),
    ("terms", "Terms of Use", "Terms of Use — Pawstcard",
     "The rules for using the Pawstcard website: the early-access waitlist, the Journal, and what is and is not promised."),
    ("about", "About Pawstcard", "About Pawstcard",
     "Pawstcard is a report-card tool for independent pet sitters and dog walkers. Learn what it does and who is behind it."),
    ("contact", "Contact", "Contact — Pawstcard",
     "How to reach the Pawstcard team, and how to ask for your waitlist data to be removed or corrected."),
]
DIFF_RE = re.compile(r"^##\s+(?:Differences|Legal review pending)\b.*$", re.M)


def page_url(slug):
    return "%s/%s/" % (bj.SITE, slug)


def page_body(src):
    """The published part of a manuscript."""
    m = DIFF_RE.search(src)
    return src[:m.start()] if m else src


def internal_notes(src):
    """Owner-only text that slipped into the published part of a manuscript (empty list = clean)."""
    return sorted(set(INTERNAL_RE.findall(page_body(src))))


def render_page(slug, h1, title, desc, src, v):
    url = page_url(slug)
    body = bj.markdown(bj.drop_title_h1(page_body(src), h1))
    data = {"@context": "https://schema.org", "@type": "AboutPage" if slug == "about" else "ContactPage" if slug == "contact" else "WebPage",
            "name": h1, "description": desc, "url": url, "inLanguage": "en", "isPartOf": {"@type": "WebSite", "name": "Pawstcard", "url": bj.SITE + "/"},
            "publisher": dict(bj.ORG, logo=dict(bj.APP_ICON))}
    crumbs = {"@context": "https://schema.org", "@type": "BreadcrumbList",
              "itemListElement": [{"@type": "ListItem", "position": 1, "name": "Pawstcard", "item": bj.SITE + "/"},
                                  {"@type": "ListItem", "position": 2, "name": h1, "item": url}]}
    head = bj.head(title, desc, url, v, False, bj.ld(data) + bj.ld(crumbs), alternates=bj.alt_links(url))
    head = head.replace("edit journal/posts/*.md and rebuild", "edit legal/*.md and run scripts/build_legal.py")
    head = head.replace(bj.GEN_MARK, "generated by scripts/build_legal.py")
    return (head + f"""<main class="wrap article-wrap">
  <article class="article legal">
    <header class="article-head">
      <h1>{bj.esc(h1)}</h1>
    </header>
    <div class="prose">
{body}
    </div>
  </article>
</main>
""" + bj.footer())


def build(root, check_only=False):
    """Returns (problems, warnings). Writes pages unless check_only."""
    root = Path(root).resolve()
    v = bj.asset_v(root)
    problems, warnings = [], []
    for slug, h1, title, desc in PAGES:
        src_path = root / SRC_DIR / (slug + ".md")
        if not src_path.exists():
            problems.append("%s: missing" % src_path.relative_to(root))
            continue
        src = src_path.read_text(encoding="utf-8")
        out = render_page(slug, h1, title, desc, src, v)
        target = root / slug / "index.html"
        if check_only:
            if not target.exists() or target.read_text(encoding="utf-8") != out:
                problems.append("%s/index.html is missing or out of date — run scripts/build_legal.py" % slug)
        else:
            target.parent.mkdir(parents=True, exist_ok=True)
            target.write_text(out, encoding="utf-8")
        leaked = internal_notes(src)
        if leaked:
            problems.append("%s.md: internal note in the published text (%s) — move it under '## Legal review pending'" % (slug, ", ".join(leaked[:5])))
    return problems, warnings


def main(argv=None):
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--root", default=str(ROOT))
    ap.add_argument("--check", action="store_true", help="write nothing; fail if a generated page is missing or out of date")
    a = ap.parse_args(argv)
    problems, warnings = build(a.root, a.check)
    if problems:
        print("legal: errors\n  " + "\n  ".join(problems), file=sys.stderr)
        return 1
    for w in warnings:
        print("  warning: " + w)
    print("legal: %s — %d pages" % ("OK" if a.check else "built", len(PAGES)))
    return 0


if __name__ == "__main__":
    sys.exit(main())
