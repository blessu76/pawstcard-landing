#!/usr/bin/env python3
"""Build /privacy/ and /terms/ as redirects to the ipe.rest legal pages.

    python3 scripts/build_legal.py            # write <slug>/index.html redirect for each page
    python3 scripts/build_legal.py --check    # write nothing; fail if a redirect is missing or out of date

The manuscripts in legal/*.md are the source of the ipe.rest legal pages; they are not published here.
The build fails if a manuscript still carries an HTML comment, a Korean character or an internal reference.
"""
import argparse
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
SRC_DIR = "legal"
TARGET = "https://ipe.rest/en/legal/%s/"
PAGES = [
    # slug, <h1>, <title>, meta description
    ("privacy", "Privacy Policy", "Privacy Policy — Pawstcard",
     "The Pawstcard Privacy Policy has moved to ipe.rest."),
    ("terms", "Terms of Use", "Terms of Use — Pawstcard",
     "The Pawstcard Terms of Use have moved to ipe.rest."),
]
INTERNAL_RE = re.compile(r"<!--|-->|[ㄱ-ㆎ가-힣]|Quill|_ipe")


def internal_problems(src):
    return sorted(set(INTERNAL_RE.findall(src)))


def redirect_page(slug, h1, title, desc):
    url = TARGET % slug
    return f"""<!DOCTYPE html>
<html lang="en">
<head>
<meta charset="UTF-8">
<meta name="viewport" content="width=device-width, initial-scale=1.0">
<!-- generated by scripts/build_legal.py — do not hand-edit -->
<title>{title}</title>
<meta name="description" content="{desc}">
<meta name="robots" content="noindex,follow">
<link rel="canonical" href="{url}">
<meta http-equiv="refresh" content="0; url={url}">
</head>
<body>
<main>
  <h1>{h1}</h1>
  <p>Redirecting… <a href="{url}">click here</a> if you are not redirected.</p>
</main>
</body>
</html>
"""


def build(root, check_only=False):
    """Returns a list of problems. Writes redirect pages unless check_only."""
    root = Path(root).resolve()
    problems = []
    for slug, h1, title, desc in PAGES:
        src_path = root / SRC_DIR / (slug + ".md")
        if not src_path.exists():
            problems.append("%s: missing" % src_path.relative_to(root))
            continue
        leaked = internal_problems(src_path.read_text(encoding="utf-8"))
        if leaked:
            problems.append("%s: internal text in the manuscript (%s)" % (src_path.relative_to(root), ", ".join(leaked)))
            continue
        out = redirect_page(slug, h1, title, desc)
        target = root / slug / "index.html"
        if check_only:
            if not target.exists() or target.read_text(encoding="utf-8") != out:
                problems.append("%s/index.html is missing or out of date — run scripts/build_legal.py" % slug)
        else:
            target.parent.mkdir(parents=True, exist_ok=True)
            target.write_text(out, encoding="utf-8")
    return problems


def main(argv=None):
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--root", default=str(ROOT))
    ap.add_argument("--check", action="store_true", help="write nothing; fail if a redirect is missing or out of date")
    a = ap.parse_args(argv)
    problems = build(a.root, a.check)
    if problems:
        print("legal: errors\n  " + "\n  ".join(problems), file=sys.stderr)
        return 1
    print("legal: %s — %d redirects" % ("OK" if a.check else "built", len(PAGES)))
    return 0


if __name__ == "__main__":
    sys.exit(main())
